def family_for(speciality: str) -> str:
    s = (speciality or "").lower()
    for key, family in _KEYWORDS:
        if key in s:
            return family
    return DEFAULT_FAMILY


def past_disciplines(speciality: str, semester: int, per_semester: int = 7) -> list[str]:
    """Дисциплины семестра `semester` (1, 2, …): 3 из общего ядра + остальное из профиля."""
    fam = FAMILIES[family_for(speciality)]
    core_n = 3 if semester <= 4 else 2
    prof_n = per_semester - core_n
    core = [CORE[((semester - 1) * core_n + i) % len(CORE)] for i in range(core_n)]
    prof = [fam[((semester - 1) * prof_n + i) % len(fam)] for i in range(prof_n)]
    out: list[str] = []
    for d in core + prof:
        if d not in out:
            out.append(d)
    return out


