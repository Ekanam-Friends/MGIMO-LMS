def feminine_surname(surname: str) -> str:
    if surname.endswith("ий"):
        return surname[:-2] + "ая"
    return surname + "а"


_feminine = feminine_surname


def allowed_surnames(forbidden: Collection[str]) -> tuple[str, ...]:
    """Фамилии из списка, которые не совпадают ни с одной фамилией из `forbidden` ни в одном роде.

    В `forbidden` передаются фамилии реальных преподавателей: вымышленный «Харитонов» рядом
    с реальной «Харитоновой» выглядел бы как настоящий человек, даже если это случайность.
    """
    blocked = {s.casefold() for s in forbidden}
    allowed = tuple(
        s for s in _SURNAMES if s.casefold() not in blocked and _feminine(s).casefold() not in blocked
    )
    if not allowed:
        raise RuntimeError("все вымышленные фамилии совпали с реальными — расширь список")
    return allowed


def _candidate(oid: int, salt: str, attempt: int, surnames: Sequence[str]) -> str:
    digest = hashlib.sha256(f"{salt}:{oid}:{attempt}".encode()).digest()
    pick = int.from_bytes(digest[:8], "big")
    female = pick & 1
    pick >>= 1
    surname = surnames[pick % len(surnames)]
    pick //= len(surnames)
    names = _FEMALE_NAMES if female else _MALE_NAMES
    first = names[pick % len(names)]
    pick //= len(names)
    patronymic = _PATRONYMICS[pick % len(_PATRONYMICS)][female]
    if female:
        surname = _feminine(surname)
    return f"{surname} {first} {patronymic}"


def fake_teacher_name(
    oid: int,
    salt: str,
    taken: Container[str] = (),
    surnames: Sequence[str] = _SURNAMES,
) -> str:
    """Вымышленное ФИО для преподавателя с oid; не совпадает ни с одним из `taken`.

    `surnames` — разрешённые фамилии, обычно результат `allowed_surnames(...)`.
    """
    for attempt in range(1000):
        name = _candidate(oid, salt, attempt, surnames)
        if name not in taken:
            return name
    raise RuntimeError("не удалось подобрать свободное вымышленное ФИО")
